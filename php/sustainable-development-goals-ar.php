                            <li><strong>مبادرات تحسين الجودة:</strong> تُعطي الأولوية لتحسين جودة التعليم من خلال أساليب وموارد تعليمية مبتكرة.</li>
                            <li><strong>التركيز على المساواة:</strong> العمل على إزالة العوائق التي تواجهها الفئات المحرومة في الحصول على تعليم جيد.</li>
                            <li><strong>تعزيز التعلم مدى الحياة:</strong> تشجيع التعلم مدى الحياة من خلال توفير مسارات تعليمية متنوعة، بما في ذلك التدريب المهني.</li>
