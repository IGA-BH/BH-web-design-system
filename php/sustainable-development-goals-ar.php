                            <li><strong>التعلّم الجيد:</strong> تحسين جودة التعليم من خلال تحسين أساليب التدريس والمناهج الدراسية وموارد التعلّم.</li>
                            <li><strong>الإنصاف في التعليم:</strong> معالجة التفاوتات في فرص الحصول على التعليم ونتائجه للفئات المهمّشة والمحرومة.</li>
                            <li><strong>التعلّم مدى الحياة:</strong> تعزيز فرص التعلّم مدى الحياة للجميع، بما في ذلك التعليم المهني والتقني.
