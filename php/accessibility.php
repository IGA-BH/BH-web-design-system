                <h2>Our Commitment</h2>
                <p>We are dedicated to making this government website accessible and usable for everyone, including people with disabilities. Our goal is to ensure all users can independently, effectively, and efficiently access services and information. Accessibility is an ongoing priority that is deeply integrated into our organizational culture, design, and development processes.</p>
                <h3>Accessibility Standards</h3>
                <p>This website aims to conform to the Government Design System (GDS) standards and meets or exceeds the Web Content Accessibility Guidelines (WCAG) 2.1 Level AA criteria, with ongoing efforts to achieve Level AAA where feasible.</p>
                <h3>Key Features</h3>
                <ul>
                    <li>Responsive design for mobile, tablet, and desktop devices</li>
                    <li>Dark mode and high contrast options</li>
                    <li>Adjustable text size without loss of content or layout integrity</li>
                    <li>Keyboard navigation support including skip links and clear focus indicators</li>
                    <li>Descriptive link text for clarity</li>
                    <li>Alternative (Alt) text provided for all meaningful images</li>
                    <li>Audio and video controls, captions available, and screen reader compatibility</li>
                </ul>
                <h3>Zoom and Navigation</h3>
                <ul>
                    <li>Users can zoom in up to 300% without any loss of content or functionality</li>
                    <li>Most website pages are fully navigable via keyboard</li>
                    <li>Content pages support navigation using speech recognition software</li>
                </ul>
                <h3>Compatibility</h3>
                <p>This website is compatible with the latest versions of major web browsers, including Google Chrome, Firefox, Safari, Microsoft Edge, and Samsung Browser. We recommend keeping your browser updated for improved security and functionality. The site is also designed responsively to display properly on various screen sizes and resolutions across mobile and desktop devices.</p>
                <h3>Users with Special Needs</h3>
                <p>We consider the needs of all users, including those with disabilities. Features such as screen-reader compatibility help users with vision impairments access content easily. Recommended free screen-reader programs include NVDA and System Access to Go, along with built-in Text-to-Speech features.</p>
                <h3>Font Size and Contrast</h3>
                <p>Users can increase/decrease text size or switch between contrast modes using built-in site controls.</p>
                <h3>JavaScript and PDF Accessibility</h3>
                <p>JavaScript is used throughout the website to enhance usability; please enable it in your browser for the best experience. To view downloadable PDF files, Acrobat Reader or compatible software is required.</p>
                <h3>Third-Party Content</h3>
                <p>Some third-party content and services embedded on this website may not yet meet our accessibility standards. We are actively working with vendors to improve this. Where accessible alternatives exist, we strive to provide them to ensure equal access.</p>
                <h3>Ongoing Improvements</h3>
                <p>We regularly conduct accessibility audits using both automated tools and manual testing. Accessibility checks are embedded throughout our design and development lifecycle. User feedback plays a vital role in prioritizing improvements.</p>
                <h3>Reporting Accessibility Issues</h3>
                <p>Your feedback is invaluable to help us enhance the website’s accessibility. If you encounter any barriers or believe we are not meeting accessibility requirements, please reach out to us. You can find contact details on the “<a href="contact-us.html">Contact Us</a>” page.</p>
