                <div class="govbh-abstract">
                    <p>إن خصوصيتك مهمة بالنسبة لنا. توضح سياسة الخصوصية هذه كيفية جمعنا واستخدامنا ومشاركتنا وحمايتنا لمعلوماتك الشخصية عند زيارتك أو تفاعلك مع موقعنا الإلكتروني. نحن ملتزمون بمعالجة بياناتك وفقًا لقانون حماية البيانات الشخصية لمملكة البحرين.</p>
                </div>
                <p>باستخدامك لهذا الموقع، فإنك توافق على الممارسات الموضحة أدناه.</p>
                <h2>المعلومات التي نجمعها</h2>
                <p>قد نقوم بجمع نوعين من البيانات الشخصية:</p>
                <p><strong>أ. المعلومات التي تقدمها مباشرةً</strong></p>
                <p>تشمل المعلومات التي تُدخلها عند تعبئة النماذج، أو التسجيل للحصول على الخدمات، أو التواصل معنا، مثل: الاسم، عنوان البريد الإلكتروني، رقم الهاتف، وأي معلومات تعريف أو تواصل ذات صلة.</p>
                <p><strong>ب. المعلومات التي يتم جمعها تلقائيًا</strong></p>
                <p>نقوم بجمع بيانات تقنية بشكل تلقائي من خلال ملفات تعريف الارتباط "Cookies" وأدوات التحليل عند زيارتك لموقعنا، وتشمل: عنوان بروتوكول الإنترنت "IP"، نوع المتصفح والجهاز، نظام التشغيل، الصفحات التي تمت زيارتها، الوقت المستغرق في الموقع، وأنماط الاستخدام.</p>
                <h3>الأساس القانوني للمعالجة البيانات</h3>
                <p>نقوم بجمع ومعالجة بياناتك الشخصية بناءً على واحد أو أكثر من الأسس القانونية التالية، وفقًا لقانون حماية البيانات الشخصية لمملكة البحرين:</p>
                <ul>
                    <li>أداء مهمة في المصلحة العامة أو بموجب سلطة رسمية.</li>
                    <li>للرد على طلباتك أو تقديم الخدمات.</li>
                    <li>للامتثال للالتزامات القانونية أو التنظيمية.</li>
                    <li>بناءً على موافقتك، حيثما ينطبق ذلك.</li>
                </ul>
                <h3>كيفية استخدام معلوماتك</h3>
                <p>تُستخدم معلوماتك الشخصية لأغراض مشروعة ومحددة فقط، مثل:</p>
                <ul>
                    <li>تقديم وتحسين الخدمات العامة أو الإدارية.</li>
                    <li>الرد على الاستفسارات أو الطلبات.</li>
                    <li>إرسال إشعارات متعلقة بالخدمات.</li>
                    <li>ضمان تشغيل الموقع الإلكتروني وأمنه.</li>
                    <li>تلبية المتطلبات القانونية أو الوظيفية.</li>
                </ul>
                <h3>استخدام ملفات تعريف الارتباط وتقنيات التتبع</h3>
                <p>نستخدم ملفات تعريف الارتباط "Cookies" والتقنيات المشابهة من أجل:</p>
                <ul>
                    <li>تذكر تفضيلاتك</li>
                    <li>تحسين الأداء وسهولة الاستخدام</li>
                    <li>تحليل بيانات استخدام الموقع والتوجهات</li>
                </ul>
                <p>يمكنك إدارة ملفات تعريف الارتباط أو تعطيلها من خلال إعدادات متصفحك. يُرجى العلم أن تعطيل ملفات تعريف الارتباط قد يؤثر على بعض ميزات الموقع أو أدائه.</p>
                <h3>مشاركة معلوماتك</h3>
                <p>نحن لا نبيع أو نتاجر ببياناتك الشخصية. قد يتم مشاركة المعلومات في ظروف محدودة وضرورية فقط:</p>
                <ul>
                    <li>مع الجهات الحكومية الأخرى حسب الحاجة للقيام بالواجبات الرسمية.</li>
                    <li>مع الجهات التنظيمية أو السلطات القانونية، حيثما يُطلب قانونيًا أو لحماية السلامة العامة.</li>
                </ul>
                <h3>إجراءات الأمان</h3>
                <p>نُطبّق إجراءات وقائية إدارية وتقنية ومادية - بما في ذلك التشفير، وضوابط الوصول، والتقييمات الأمنية الدورية - لحماية بياناتك من الوصول أو التعديل أو الكشف أو الإتلاف غير المصرح به.</p>
                <h3>الروابط الخارجية</h3>
                <p>قد يحتوي هذا الموقع على روابط لمواقع إلكترونية تابعة لأطراف ثالثة أو صفحات رسمية على وسائل التواصل الاجتماعي. نحن غير مسؤولين عن المحتوى أو ممارسات الخصوصية الخاصة بتلك المنصات الخارجية. نوصي بمراجعة سياسات الخصوصية الخاصة بها بشكل مستقل.</p>
                <h3>التغييرات على هذه السياسة</h3>
                <p>قد نقوم بتحديث سياسة الخصوصية هذه من وقت لآخر. سيتم دائمًا نشر النسخة الأحدث على هذه الصفحة، مع تاريخ آخر تحديث. يُرجى مراجعة السياسة بشكل دوري.</p>
                <h3>موافقتك</h3>
                <p>باستخدامك هذا الموقع، فإنك توافق على جمع واستخدام معلوماتك كما هو موضح في هذه السياسة. في حال عدم موافقتك، يُرجى عدم استخدام موقعنا.</p>
                <h3>تواصل معنا </h3>
                <p>إذا كانت لديك أسئلة أو طلبات تتعلق بسياسة الخصوصية هذه أو بياناتك الشخصية، يُرجى التواصل معنا. يمكنك العثور على معلومات الاتصال في صفحة "<a href="contact-us.html">تواصل معنا</a>".</p>
