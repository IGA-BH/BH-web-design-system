                </div>
                <h2>غرض استخدام الكوكيز</h2>
                <p>تُستخدم ملفات تعريف الارتباط على هذا الموقع للأغراض التالية:</p>
                <ul>
                    <li>ضمان عمل الموقع الإلكتروني بأمان وكفاءة.</li>
                    <li>تذكُّر تفضيلات المستخدم مثل اللغة أو إعدادات إمكانية الوصول.</li>
                    <li>دعم التحليل الإحصائي لأغراض التقييم الداخلي وتحسين النظام.</li>
                </ul>
                <p>لا تُستخدم ملفات تعريف الارتباط لأغراض التسويق، أو التتبع عبر المواقع، أو الإعلانات من أطراف ثالثة.</p>
                <h2>تخزين الكوكيز ومشاركة البيانات</h2>
                <p>تُخزَّن ملفات تعريف الارتباط محليًا على جهاز المستخدم لفترة زمنية محددة تختلف حسب نوع الكوكيز ووظيفته. وتُستخدم البيانات التي يتم جمعها من خلال الكوكيز فقط لأغراض تشغيلية وتحليلية. ولا يتم مشاركتها مع أي أطراف ثالثة إلا إذا تطلّب القانون ذلك أو في حالة التعاقد مع مزودي خدمات خارجيين لدعم فني محدد، وفي هذه الحالات تُطبق التزامات صارمة تتعلق بالسرية وحماية البيانات. لا يتم بيع أو تصنيف أو الكشف عن أي بيانات شخصية لأغراض تجارية.</p>
                <h2>أنواع الكوكيز المستخدمة</h2>
                <p>قد تُستخدم الفئات التالية من الكوكيز على هذا الموقع الإلكتروني:</p>
                <ul>
                    <li><strong>ملفات تعريف الارتباط الضرورية للغاية:</strong> ضرورية لتشغيل الموقع، وتشمل إدارة الجلسات، والأمان، والتحكم في الوصول.</li>
                    <li><strong>كوكيز الأداء والتحليلات:</strong> تجمع معلومات مجهولة المصدر حول استخدام الموقع وأدائه لدعم تحسينه ومعالجة المشكلات.</li>
                    <li><strong>كوكيز الوظائف:</strong> تُمكّن الموقع من تذكّر اختيارات المستخدم (مثل اللغة أو تفضيلات العرض) لتوفير تجربة متسقة.</li>
                </ul>
                <h2>إدارة الكوكيز</h2>
                <p>يمكن للمستخدمين التحكم في استخدام الكوكيز من خلال إعدادات المتصفح. تتيح معظم المتصفحات الحديثة للمستخدمين:</p>
                <ul>
                    <li>عرض ملفات الكوكيز المخزنة وحذفها.</li>
                    <li>حظر الكوكيز من مواقع معينة.</li>
                    <li>تعطيل جميع الكوكيز تمامًا.</li>
                </ul>
                <p>يرجى ملاحظة أن تعطيل بعض أنواع الكوكيز، خاصة الكوكيز الضرورية للغاية، قد يؤثر على وظائف الموقع أو إمكانية الوصول إليه.</p>
                <p>تسمح معظم المتصفحات بالتحكم في الكوكيز من خلال إعداداتها. لمزيد من التفاصيل، يُرجى الرجوع إلى صفحات المساعدة الخاصة بالمتصفح.</p>
                <h2>التعديلات على هذه السياسة</h2>
