                <h2>التزامنا</h2>
                <p>نحن ملتزمون بجعل هذا الموقع الحكومي متاحًا وسهل الاستخدام للجميع، بما في ذلك الأشخاص ذوي الإعاقة. هدفنا هو ضمان قدرة جميع المستخدمين على الوصول إلى الخدمات والمعلومات بشكل مستقل وفعّال وكفؤ. وتُعد إمكانية الوصول أولوية مستمرة متجذّرة في ثقافتنا التنظيمية وعمليات التصميم والتطوير لدينا.</p>
                <h3>معايير إمكانية الوصول</h3>
                <p>يلتزم هذا الموقع بتطبيق معايير نظام التصميم الحكومي (GDS)، ويتوافق مع إرشادات الوصول إلى محتوى الويب (WCAG 2.1) بمستوى AA أو أعلى، ويعمل باستمرار على تحقيق مستوى AAA كلما كان ذلك ممكنًا.</p>
                <h3>الميزات الرئيسية</h3>
                <ul>
                    <li>تصميم متجاوب يدعم الهواتف المحمولة، والأجهزة اللوحية، وأجهزة سطح المكتب.</li>
                    <li>وضع داكن وخيارات تباين عالٍ.</li>
                    <li>إمكانية تعديل حجم النص دون التأثير على المحتوى أو تنسيق الصفحة.</li>
                    <li>دعم كامل للتنقل باستخدام لوحة المفاتيح، بما في ذلك روابط التجاوز ومؤشرات تركيز واضحة.</li>
                    <li>نصوص وصفية للروابط لضمان الوضوح وسهولة الفهم.</li>
                    <li>توفير نص بديل (Alt) لجميع الصور ذات الدلالة.</li>
                    <li>عناصر تحكم بالصوت والفيديو، مع توفر ترجمات وتوافق مع قارئات الشاشة.</li>
                </ul>
                <h3>تكبير الشاشة والتنقل</h3>
                <ul>
                    <li>يمكن للمستخدمين التكبير حتى 300% دون فقدان المحتوى أو الوظائف.</li>
                    <li>معظم صفحات الموقع قابلة للتنقل عبر لوحة المفاتيح.</li>
                    <li>تدعم صفحات المحتوى التنقل باستخدام برامج التعرف على الصوت·</li>
                </ul>
                <h3>التوافق</h3>
                <p>هذا الموقع متوافق مع أحدث إصدارات المتصفحات الرئيسية، بما في ذلك جوجل كروم، فايرفوكس، سفاري، مايكروسوفت إيدج، ومتصفح سامسونج. ننصحك بالحفاظ على تحديث متصفحك لتحسين الأمان والوظائف. كما أن الموقع مصمم بشكل استجابة ليعرض بشكل صحيح على مختلف أحجام ودقات الشاشات عبر الأجهزة المحمولة وسطح المكتب.</p>
                <h3>المستخدمون ذوي الاحتياجات الخاصة</h3>
                <p>نأخذ في الاعتبار احتياجات جميع المستخدمين، بما في ذلك ذوي الإعاقات. تساعد ميزات مثل التوافق مع برامج قراءة الشاشة المستخدمين الذين يعانون من ضعف البصر على الوصول إلى المحتوى بسهولة. من البرامج المجانية الموصى بها لقراءة الشاشة NVDA وSystem Access to Go، بالإضافة إلى ميزات تحويل النص إلى كلام المدمجة.</p>
                <h3>حجم الخط والتباين</h3>
                <p>يمكن للمستخدمين زيادة أو تقليل حجم النص أو التبديل بين أوضاع التباين باستخدام أدوات التحكم المدمجة في الموقع.</p>
                <h3>جافا سكريبت وإمكانية الوصول إلى ملفات PDF</h3>
                <p>يُستخدم جافا سكريبت (JavaScript) في الموقع لتعزيز سهولة الاستخدام؛ يرجى تفعيله في متصفحك للحصول على أفضل تجربة. لمشاهدة ملفات PDF القابلة للتحميل، يلزم وجود برنامج Acrobat Reader أو برنامج متوافق.</p>
                <h3>محتوى الطرف الثالث</h3>
                <p>قد لا تلتزم بعض المحتويات والخدمات التابعة لأطراف ثالثة المدمجة في هذا الموقع بمعايير إمكانية الوصول الخاصة بنا. نحن نعمل بجد مع البائعين لتحسين ذلك. وعندما تتوفر بدائل قابلة للوصول، نسعى لتوفيرها لضمان وصول متساويٍ للجميع.</p>
                <h3>التحسينات المستمرة</h3>
                <p>نقوم بانتظام بإجراء مراجعات لإمكانية الوصول باستخدام أدوات تلقائية واختبارات يدوية. وتُدمج فحوصات إمكانية الوصول في كافة مراحل التصميم والتطوير. كما تأخذ ملاحظات المستخدمين بعين الاعتبار عند تحديد أولويات التحسينات.</p>
                <h3>الإبلاغ عن مشاكل إمكانية الوصول</h3>
                <p>ملاحظاتكم ثمينة جداً لمساعدتنا في تحسين إمكانية الوصول إلى الموقع. إذا واجهت أي عقبات أو تعتقد أننا لا نلبي متطلبات إمكانية الوصول، يرجى التواصل معنا. يمكنكم العثور على بيانات الاتصال في صفحة "<a href="contact-us.html">اتصل بنا</a>".</p>
