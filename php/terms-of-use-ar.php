                    <li>محاولة الوصول غير المصرح به إلى الأنظمة أو البيانات.</li>
                    <li>نشر أو إرسال أي مواد ضارة أو مسيئة أو تشهيرية أو غير مقبولة.</li>
                    <li>استخدام الموقع لتوزيع الرسائل الإلكترونية غير المرغوب فيها أو البرمجيات الخبيثة أو أي تقنيات ضارة أخرى.</li>
                </ul>
